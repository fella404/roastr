class Product {
  final String id;
  final String name;
  final String image;
  final double price;
  final String categoryId;
  final String categoryName;
  final String categoryIcon;

  const Product({
    required this.id,
    required this.name,
    required this.image,
    required this.price,
    required this.categoryId,
    required this.categoryName,
    required this.categoryIcon,
  });
}
